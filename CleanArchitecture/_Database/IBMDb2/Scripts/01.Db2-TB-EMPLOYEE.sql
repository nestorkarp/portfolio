CREATE SCHEMA "RH" AUTHORIZATION "DB2MANAGER";

CREATE TABLE "RH"."EMPLOYEE" (
		"ELE_ID" INTEGER NOT NULL GENERATED ALWAYS AS IDENTITY ( START WITH 1 INCREMENT BY 1 MINVALUE -2147483648 MAXVALUE 2147483647 NO CYCLE CACHE 20 NO ORDER ), 
		"ELE_IDENTITYCARD" VARCHAR(11 OCTETS) NOT NULL, 
		"ELE_FIRSTNAME" VARCHAR(30 OCTETS) NOT NULL, 
		"ELE_LASTNAME" VARCHAR(30 OCTETS) NOT NULL, 
		"ELE_BIRTHDATE" DATE NOT NULL, 
		"ELE_ACTIVE" SMALLINT NOT NULL, 
		"ELE_AUDIT_DATETIME" TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP
	)
	ORGANIZE BY ROW
	DATA CAPTURE NONE 
	IN "USERSPACE1"
	COMPRESS NO;

CREATE UNIQUE INDEX "RH"."EMPLOYEE_IDX_IDENTITYCARD"
	ON "RH"."EMPLOYEE"
	("ELE_IDENTITYCARD"		ASC)
	MINPCTUSED 0
	ALLOW REVERSE SCANS
	PAGE SPLIT SYMMETRIC
	COLLECT SAMPLED DETAILED STATISTICS
	COMPRESS NO;

ALTER TABLE "RH"."EMPLOYEE" ADD CONSTRAINT "SQL260916171911140" PRIMARY KEY
